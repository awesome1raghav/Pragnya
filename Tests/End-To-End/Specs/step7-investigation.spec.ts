/* Step 7 end-to-end: an uploaded photo's run builds the evidence graph and the reconstruction; the investigator records a
   case conclusion on the Review tab; a FINAL report is generated by the worker and its PDF downloads with the SHA-256
   the page shows. */
import { expect, test, type Page } from '@playwright/test';
import crypto from 'node:crypto';
import path from 'node:path';

const API = process.env.NEXTRON_API ?? 'http://localhost:8002/api/v1';
const SHOTS = path.join(__dirname, '..', '..', 'Test Reports', 'End-To-End', 'Screenshots');
const shot = (page: Page, name: string) => page.screenshot({ path: path.join(SHOTS, `${name}.png`), fullPage: true });

let problems: string[] = [];
test.beforeEach(async ({ page }) => {
  problems = [];
  page.on('pageerror', e => problems.push(`pageerror: ${e.message}`));
  page.on('console', m => { if (m.type() === 'error' && !/status of (404|409|422)/.test(m.text())) problems.push(`console: ${m.text()}`); });
});
test.afterEach(() => { expect(problems, problems.join('\n')).toEqual([]); });

test('graph, reconstruction, review and a final report', async ({ page }) => {
  test.setTimeout(180_000);
  const c = (await (await fetch(`${API}/cases`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ title: `[E2E] Review ${Date.now()}` }) })).json()).data;
  await page.goto(`/investigations/${c.case_id}/evidence/add`);
  await expect(page.getByText(/MB per file/)).toBeVisible();
  const png = await page.evaluate(() => {
    const cv = document.createElement('canvas'); cv.width = 320; cv.height = 240;
    const g = cv.getContext('2d')!; g.fillStyle = '#2a6f97'; g.fillRect(0, 0, 320, 240); g.fillStyle = '#e9a23b'; g.fillRect(80, 60, 160, 120);
    return cv.toDataURL('image/png').split(',')[1];
  });
  await page.locator('input[type=file]').setInputFiles({ name: 'photo.png', mimeType: 'image/png', buffer: Buffer.from(png, 'base64') });
  await page.getByRole('button', { name: /Upload and preserve 1 file/ }).click();
  await expect(page.getByRole('region', { name: 'Upload queue' })).toContainText(/analysis JOB-\d+ queued/);

  await page.goto(`/investigations/${c.case_id}/graph`);
  const edges = page.getByRole('group', { name: 'Graph edges' });
  await expect(edges).toBeVisible({ timeout: 90_000 });  // built at the end of the run
  await edges.locator('summary').click();  // the edge list is one level down, behind the drawing
  await expect(page.getByRole('img', { name: /nodes, \d+ edges/ })).toBeVisible();
  await expect(edges).toContainText('analysis_findings:');
  await shot(page, '30-graph');

  await page.goto(`/investigations/${c.case_id}/timeline`);
  await expect(page.getByRole('region', { name: 'Reconstruction' })).toContainText('Received by NEXTRON');

  await page.goto(`/investigations/${c.case_id}/review`);
  const form = page.getByRole('region', { name: 'Record a decision' });
  await form.getByRole('combobox', { name: 'Review subject' }).selectOption(`CASE_CONCLUSION:${c.case_id}`);
  await form.getByRole('combobox', { name: 'Decision' }).selectOption('INCONCLUSIVE');
  await form.getByRole('textbox', { name: 'Rationale' }).fill('One synthetic image and no source');
  await form.getByRole('button', { name: 'Record decision' }).click();
  await expect(page.getByRole('region', { name: 'Current decisions' })).toContainText(/REV-\d+ · Case conclusion/);
  await expect(page.getByRole('region', { name: 'Current decisions' })).toContainText('Inconclusive');
  await shot(page, '31-review');

  await page.goto(`/investigations/${c.case_id}/report`);
  await page.getByRole('button', { name: 'Final report' }).click();
  const row = page.getByRole('listitem', { name: /RPT-\d+ version 1/ });
  await expect(row).toContainText('Generated', { timeout: 60_000 });
  await expect(row).toContainText('conclusion inconclusive');
  const [download] = await Promise.all([page.waitForEvent('download'), row.getByRole('link', { name: /PDF/ }).click()]);
  const bytes = await (await import('node:fs/promises')).readFile((await download.path())!);
  expect(bytes.subarray(0, 4).toString()).toBe('%PDF');
  await expect(row).toContainText(crypto.createHash('sha256').update(bytes).digest('hex'));
  await shot(page, '32-report');
});
