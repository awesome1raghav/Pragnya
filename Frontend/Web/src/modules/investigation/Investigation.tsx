export function CaseGraph({ caseId, caseNumber }: { caseId: string; caseNumber: string }) {
  return <div className={s.page}>
    <PageHead title='Evidence graph' desc={`${caseNumber} · built by NEX-EGC from stored records only. Every edge names the record that supports it.`} />
    <GraphView caseId={caseId} />
  </div>;
}

function GraphView({ caseId }: { caseId: string }) {
  const q = useGraph(caseId);
  if (q.error && notBuilt(q.error)) return <Empty title='No graph yet'>The graph is built at the end of each analysis run. Add evidence or start a run.</Empty>;
  return <Load q={q} rows={5}>{g => <GraphExplorer g={g} />}</Load>;
}

const EDGE_LABEL: Record<string, string> = { RETRIEVED_AS: 'Retrieved as', CANDIDATE_VERSION: 'Candidate version', ABOUT: 'Finding about', CITES: 'Cites' };
const EDGE_COLOR: Record<string, string> = { RETRIEVED_AS: '#7fa6bf', CANDIDATE_VERSION: '#e9a23b', ABOUT: '#6d675e', CITES: '#b98fd6' };

/* Progressive exploration: relationships first (sources, candidate versions, citations), findings about evidence on
   request; inferences before observations. Selecting a node keeps its neighbours lit and opens what it stands for.
   Every edge drawn is a stored record; candidate versions stay dashed because they are candidates. */
function GraphExplorer({ g }: { g: GraphSnapshot }) {
  const present = [...new Set(g.edges.map(e => e.type).filter(t => t !== 'CONTAINS'))];
  const [types, setTypes] = useState<Set<string>>(() => new Set(present.filter(t => t !== 'ABOUT' || g.counts.nodes_finding <= 12)));
  const [observations, setObservations] = useState(false);
  const [text, setText] = useState('');
  const [selected, setSelected] = useState<string | null>(null);
  const [view, setView] = useState({ z: 1, x: 0, y: 0 });
  const [dragging, setDragging] = useState(false);
  const drag = useRef<{ x: number; y: number; vx: number; vy: number } | null>(null);
  const svg = useRef<SVGSVGElement>(null);

  const edges = g.edges.filter(e => types.has(e.type));
  const findingShown = (n: GraphNode) => n.type !== 'FINDING' || ((observations || n.assertion === 'INFERENCE') && edges.some(e => e.from === n.id || e.to === n.id));
  const nodes = g.nodes.filter(n => n.type !== 'CASE' && findingShown(n));
  const cols: Record<string, GraphNode[]> = { SOURCE: [], EVIDENCE: [], FINDING: [] };
  nodes.forEach(n => cols[n.type]?.push(n));
  const X: Record<string, number> = { SOURCE: 90, EVIDENCE: 330, FINDING: 570 }, gap = 34, top = 40;
  const rows = Math.max(1, ...Object.values(cols).map(c => c.length));
  const pos = new Map<string, { x: number; y: number }>();
  Object.entries(cols).forEach(([t, ns]) => ns.forEach((n, i) => pos.set(n.id, { x: X[t], y: top + i * gap + (rows - ns.length) * gap / 2 })));
  const h = top + rows * gap + 10;
  const needle = text.trim().toLowerCase();
  const match = (n: GraphNode) => !needle || `${String(n.label)} ${String(n.title ?? '')} ${String(n.filename ?? '')} ${String(n.module ?? '')}`.toLowerCase().includes(needle);
  const near = selected ? new Set([selected, ...edges.filter(e => e.from === selected || e.to === selected).flatMap(e => [e.from, e.to])]) : null;
  const byId = new Map(g.nodes.map(n => [n.id, n]));
  const lit = (id: string) => (!near || near.has(id)) && (!needle || match(byId.get(id)!));
  const sel = selected ? byId.get(selected) ?? null : null;

  useEffect(() => {
    const el = svg.current; if (!el) return;
    const wheel = (e: WheelEvent) => { e.preventDefault(); setView(cur => ({ ...cur, z: Math.min(4, Math.max(0.4, cur.z * (e.deltaY < 0 ? 1.12 : 1 / 1.12))) })); };
    el.addEventListener('wheel', wheel, { passive: false });
    return () => el.removeEventListener('wheel', wheel);
  }, []);

  return <div className={p.stack}>
    <p className={s.cap}>{g.counts.nodes_evidence} evidence · {g.counts.nodes_source} sources · {g.counts.nodes_finding} findings · {g.counts.edges} recorded edges. Snapshot built {utc(g.created_at)}. The graph shows what is recorded, not what is true.</p>
    <section className={s.panel} aria-label='Graph drawing'>
      <div className={gx.bar}>
        <div className={gx.chips} role='group' aria-label='Relationships shown'>{present.map(t => <button key={t} aria-pressed={types.has(t)} onClick={() => setTypes(cur => { const n = new Set(cur); if (n.has(t)) n.delete(t); else n.add(t); return n; })}>
          <i style={{ background: EDGE_COLOR[t] }} />{EDGE_LABEL[t] ?? t}<small>{g.edges.filter(e => e.type === t).length}</small></button>)}
          <button aria-pressed={observations} onClick={() => setObservations(x => !x)}>Observations too</button>
        </div>
        <label className={gx.find}><Search size={13} /><input value={text} onChange={e => setText(e.target.value)} placeholder='Find a node' aria-label='Find a node' /></label>
      </div>
      <div className={gx.stageWrap}>
        <svg ref={svg} viewBox={`0 0 760 ${h}`} role='img' aria-label={`${g.counts.nodes} nodes, ${g.counts.edges} edges`} className={gx.stage}
          onPointerDown={e => { drag.current = { x: e.clientX, y: e.clientY, vx: view.x, vy: view.y }; setDragging(true); }}
          onPointerMove={e => { const d = drag.current; if (d) setView(cur => ({ ...cur, x: d.vx + (e.clientX - d.x) / cur.z, y: d.vy + (e.clientY - d.y) / cur.z })); }}
          onPointerUp={() => { drag.current = null; setDragging(false); }} onPointerLeave={() => { drag.current = null; setDragging(false); }}>
          <g transform={`translate(380 ${h / 2}) scale(${view.z}) translate(${-380 + view.x} ${-h / 2 + view.y})`} style={{ transition: dragging ? 'none' : 'transform .25s cubic-bezier(.22,1,.36,1)' }}>
            {['Sources', 'Evidence', 'Findings'].map((t, i) => <text key={t} x={[90, 330, 570][i]} y={16} textAnchor='middle' fontSize={11} fill='#8d877c'>{t}</text>)}
            {edges.map((e, i) => {
              const a = pos.get(e.from), b = pos.get(e.to);
              if (!a || !b) return null;
              const on = lit(e.from) && lit(e.to);
              const common = { stroke: EDGE_COLOR[e.type], opacity: on ? (e.type === 'ABOUT' ? 0.5 : 0.9) : 0.08, style: { transition: 'opacity .2s' } };
              if (e.type === 'CANDIDATE_VERSION' || e.type === 'CITES') {
                const bend = (e.type === 'CITES' ? 1 : -1) * (40 + Math.abs(a.y - b.y) / 3);
                return <path key={i} d={`M${a.x} ${a.y} Q${a.x + bend} ${(a.y + b.y) / 2} ${b.x} ${b.y}`} fill='none' strokeWidth={1.6} strokeDasharray={e.type === 'CANDIDATE_VERSION' ? '4 3' : undefined} {...common}><title>{`${EDGE_LABEL[e.type]} · ${e.record}`}</title></path>;
              }
              return <line key={i} x1={a.x} y1={a.y} x2={b.x} y2={b.y} strokeWidth={1} {...common}><title>{`${EDGE_LABEL[e.type]} · ${e.record}`}</title></line>;
            })}
            {nodes.map(n => {
              const xy = pos.get(n.id); if (!xy) return null;
              const tone = n.type === 'FINDING' ? (n.assertion === 'INFERENCE' ? '#e9a23b' : '#8d877c') : n.type === 'SOURCE' ? '#7fa6bf' : '#bdb6aa';
              return <g key={n.id} opacity={lit(n.id) ? 1 : 0.25} style={{ cursor: 'pointer', transition: 'opacity .2s' }} onClick={e => { e.stopPropagation(); setSelected(cur => (cur === n.id ? null : n.id)); }}
                role='button' tabIndex={0} aria-label={`${n.type.toLowerCase()} ${String(n.label)}`} onKeyDown={e => { if (e.key === 'Enter') setSelected(n.id); }}>
                <circle cx={xy.x} cy={xy.y} r={selected === n.id ? 9 : 7} fill='#1c1a17' stroke={tone} strokeWidth={selected === n.id ? 3 : 2} />
                <text x={n.type === 'FINDING' ? xy.x + 12 : xy.x - 12} y={xy.y + 4} textAnchor={n.type === 'FINDING' ? 'start' : 'end'} fontSize={12} fill={needle && match(n) ? '#f0b85c' : '#bdb6aa'}>
                  {n.type === 'FINDING' ? `${String(n.module ?? '')} ${String(n.label).toLowerCase().replace(/_/g, ' ')}` : String(n.label)}</text>
              </g>;
            })}
          </g>
        </svg>
        {sel && <NodePanel n={sel} g={g} onClose={() => setSelected(null)} />}
      </div>
      <p className={s.cap}>{nodes.filter(n => n.type === 'FINDING').length} of {g.counts.nodes_finding} findings shown{observations ? '' : ' (inferences only)'}. Scroll to zoom, drag to pan, select a node to see its relationships.</p>
    </section>
    <details className={s.panel} aria-label='Graph edges'><summary className={gx.summary}>Edges and their records ({g.edges.filter(e => e.type !== 'CONTAINS').length})</summary><EdgeTable g={g} /></details>
  </div>;
}

function NodePanel({ n, g, onClose }: { n: GraphNode; g: GraphSnapshot; onClose: () => void }) {
  const about = g.edges.find(e => e.type === 'ABOUT' && e.from === n.id)?.to;
  const rels = g.edges.filter(e => e.type !== 'CONTAINS' && (e.from === n.id || e.to === n.id));
  const name = new Map(g.nodes.map(x => [x.id, String(x.label)]));
  const href = n.type === 'EVIDENCE' ? paths.evidence(n.id, 'analysis') : n.type === 'FINDING' && about ? `${paths.evidence(about, 'analysis')}?finding=${n.id}` : n.type === 'SOURCE' ? paths.sources(g.case_id) : null;
  return <aside className={gx.node} aria-label='Selected node'>
    <header><small>{n.type.toLowerCase()}</small><button onClick={onClose} aria-label='Close'><X size={14} /></button></header>
    <b>{n.type === 'FINDING' ? String(n.title ?? n.label) : String(n.label)}</b>
    {n.type === 'EVIDENCE' && <small>{String(n.filename ?? '')} · {String(n.media_type ?? '').toLowerCase()}</small>}
    {n.type === 'FINDING' && <small>{String(n.module)} · {String(n.assertion ?? '').toLowerCase()}</small>}
    {n.type === 'SOURCE' && <small style={{ overflowWrap: 'anywhere' }}>{String(n.url ?? '')}</small>}
    {rels.length > 0 && <ul>{rels.slice(0, 8).map((e, i) => <li key={i}>{EDGE_LABEL[e.type] ?? e.type} {e.from === n.id ? '→' : '←'} {name.get(e.from === n.id ? e.to : e.from)}</li>)}{rels.length > 8 && <li>… {rels.length - 8} more</li>}</ul>}
    {href && <Link href={href} className={gx.open}>Open {n.type === 'EVIDENCE' ? 'in the viewer' : n.type === 'FINDING' ? 'this finding in the viewer' : 'its source record'}<ArrowRight size={13} /></Link>}
  </aside>;
}

function EdgeTable({ g }: { g: GraphSnapshot }) {
  const label = new Map(g.nodes.map(n => [n.id, n.type === 'FINDING' ? `${String(n.module)} · ${String(n.title ?? n.label)}` : String(n.label)]));
  const rows = g.edges.filter(e => e.type !== 'CONTAINS');
  if (!rows.length) return <p className={s.cap}>Only the case and its evidence so far; no sources, relationships or findings about evidence.</p>;
  return <div className={p.planWrap}><table className={p.planTable}>
    <thead><tr><th>From</th><th>Relationship</th><th>To</th><th>Supporting record</th></tr></thead>
    <tbody>{rows.map((e, i) => <tr key={i}>
      <td>{label.get(e.from) ?? e.from.slice(0, 8)}</td>
      <td>{edgeLabel[e.type] ?? e.type}{e.type === 'CANDIDATE_VERSION' && <small>candidate · similarity {Number(e.similarity).toFixed(2)}</small>}</td>
      <td>{label.get(e.to) ?? e.to.slice(0, 8)}</td>
      <td><span className={s.mono} style={{ fontSize: 11, overflowWrap: 'anywhere' }}>{e.record}</span></td>
    </tr>)}</tbody>
  </table></div>;
}

/* ── review ── */
export function CaseReview({ caseId, caseNumber, archived }: { caseId: string; caseNumber: string; archived: boolean }) {
  const current = useReviews(caseId, true);
  const all = useReviews(caseId);
  const graph = useGraph(caseId);
  const subjects = useMemo(() => {
    const m = new Map<string, string>();
    for (const n of graph.data?.nodes ?? []) if (n.type === 'FINDING') m.set(n.id, `${String(n.module)} · ${String(n.title ?? n.label)}`);
    const label = new Map((graph.data?.nodes ?? []).map(n => [n.id, String(n.label)]));
    for (const e of graph.data?.edges ?? []) if (e.type === 'CANDIDATE_VERSION') m.set(e.record.split(':')[1], `${label.get(e.from)} ↔ ${label.get(e.to)} (${String(e.kind)})`);
    return m;
  }, [graph.data]);
  const conclusion = current.data?.find(r => r.subject_type === 'CASE_CONCLUSION') ?? null;
  return <div className={s.page}>
    <PageHead title='Review and decisions' desc={`${caseNumber} · your conclusions about the findings, candidate relationships and the case. They are stored as investigator decisions, versioned, and never change what the methods found.`} />
    <motion.section className={rv.hero} data-empty={!conclusion || undefined} aria-label='Case conclusion' initial={{ opacity: 0, y: 6 }} animate={{ opacity: 1, y: 0 }} transition={{ duration: .25 }}>
      <div>
        <small>Case conclusion · investigator decision</small>
        {conclusion ? <><h2>{decisionLabel[conclusion.decision]}</h2><p>{conclusion.rationale}</p>
          <p className={rv.by}><span className={s.mono}>{conclusion.review_number}</span> · version {conclusion.version} · {conclusion.reviewer} · {utc(conclusion.created_at)}</p></>
          : <><h2>Not recorded yet</h2><p>Record it below once you have reviewed the findings. A final report needs one, and a conclusion needs a completed reconstruction.</p></>}
      </div>
      {conclusion && <Dot tone={decisionTone[conclusion.decision]}>{decisionLabel[conclusion.decision]}</Dot>}
    </motion.section>
    <div className={rv.grid}>
      {archived ? <section className={s.panel}><p className={s.cap}>The investigation is archived; reopen it to record decisions.</p></section> : <ReviewForm caseId={caseId} />}
      <section className={s.panel} aria-label='Current decisions'>
        <SecHead title='Current decisions' count={current.data?.length} />
        <Load q={current} rows={3}>{rs => rs.length ? <ul className={rv.decisions}>{rs.map(r => <li key={r.review_id} className={rv.decision}>
          <span className={rv.person} aria-hidden='true'><UserRound size={14} /></span>
          <div>
            <b><span className={s.mono}>{r.review_number}</span> · {subjectLabel[r.subject_type]} <small style={{ display: 'inline' }}>v{r.version}</small></b>
            {r.subject_type !== 'CASE_CONCLUSION' && <span className={rv.subject}>{subjects.get(r.subject_id) ?? `subject ${r.subject_id.slice(0, 8)}`}</span>}
            <small><Dot tone={decisionTone[r.decision]}>{decisionLabel[r.decision]}</Dot> · {r.reviewer} · {utc(r.created_at)}</small>
            <p>{r.rationale}</p>
          </div>
        </li>)}</ul> : <Empty title='No decisions yet'>Choose a subject and record a decision with your reasons.</Empty>}</Load>
      </section>
    </div>
    <details className={`${s.panel} ${rv.history}`} aria-label='Decision history'>
      <summary>History: every version ({all.data?.length ?? 0})</summary>
      <Load q={all} rows={3}>{rs => rs.length ? <div className={p.planWrap}><table className={p.planTable}>
        <thead><tr><th>Review</th><th>Subject</th><th>Decision</th></tr></thead>
        <tbody>{rs.map(r => <tr key={r.review_id}><td>{r.review_number}<small>{utc(r.created_at)}</small></td><td>{subjectLabel[r.subject_type]} v{r.version}<small>{r.subject_type === 'CASE_CONCLUSION' ? 'this investigation' : subjects.get(r.subject_id) ?? r.subject_id.slice(0, 8)}</small></td><td>{decisionLabel[r.decision]}<small>{r.rationale}</small></td></tr>)}</tbody>
      </table></div> : <p className={s.cap}>Nothing recorded.</p>}</Load>
    </details>
  </div>;
}

function ReviewForm({ caseId }: { caseId: string }) {
  const { notify } = useWorkspace();
  const graph = useGraph(caseId);
  const rec = useReconstruction(caseId);
  const [subject, setSubject] = useState(`CASE_CONCLUSION:${caseId}`);
  const [decision, setDecision] = useState<ReviewDecision>('INCONCLUSIVE');
  const [rationale, setRationale] = useState('');
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const g = graph.data;
  const findings = g?.nodes.filter(n => n.type === 'FINDING') ?? [];
  const label = new Map(g?.nodes.map(n => [n.id, String(n.label)]) ?? []);
  const relationships = g?.edges.filter(e => e.type === 'CANDIDATE_VERSION') ?? [];
  const submit = async (ev: React.FormEvent) => {
    ev.preventDefault();
    const [subject_type, subject_id] = subject.split(':') as [ReviewSubject, string];
    setBusy(true); setError(null);
    try { const r = await api.reviews.create(caseId, { subject_type, subject_id, decision, rationale }); notify(`${r.review_number} recorded (version ${r.version})`); setRationale(''); invalidate(`case:${caseId}`); }
    catch (e) { setError(e instanceof ApiError ? e.message : 'The decision could not be recorded'); }
    finally { setBusy(false); }
  };
  return <section className={s.panel} aria-label='Record a decision'>
    <SecHead title='Record a decision' />
    <p className={rv.note}>This is your judgement, stored as an investigator decision with your reasons. The finding or relationship it is about stays exactly as the method recorded it; deciding again adds a new version.</p>
    <form onSubmit={submit} className={p.form}>
      <label className={s.field}><span>About</span><select className={s.input} value={subject} onChange={e => setSubject(e.target.value)} aria-label='Review subject'>
        <option value={`CASE_CONCLUSION:${caseId}`}>The case conclusion{rec.data?.result_id ? '' : ' (needs a reconstruction first)'}</option>
        {findings.length > 0 && <optgroup label='Findings'>{findings.map(f => <option key={f.id} value={`FINDING:${f.id}`}>{String(f.module)} · {String(f.title ?? f.label)}</option>)}</optgroup>}
        {relationships.length > 0 && <optgroup label='Candidate relationships'>{relationships.map(e => <option key={e.record} value={`RELATIONSHIP:${e.record.split(':')[1]}`}>{label.get(e.from)} ↔ {label.get(e.to)} ({String(e.kind)})</option>)}</optgroup>}
      </select></label>
      <label className={s.field}><span>Decision</span><select className={s.input} value={decision} onChange={e => setDecision(e.target.value as ReviewDecision)} aria-label='Decision'>
        {(Object.keys(decisionLabel) as ReviewDecision[]).map(d => <option key={d} value={d}>{decisionLabel[d]}</option>)}</select></label>
      <label className={s.field}><span>Rationale (required, kept with the decision)</span>
        <textarea className={s.input} rows={4} required minLength={3} maxLength={4000} value={rationale} onChange={e => setRationale(e.target.value)} aria-label='Rationale' placeholder='What you relied on, and what would change your mind' /></label>
      <button className={`${s.btn} ${s.primary}`} disabled={busy || rationale.trim().length < 3}><Plus size={15} />{busy ? 'Recording…' : 'Record decision'}</button>
    </form>
    {error && <p className={p.fieldError} role='alert'>{error}</p>}
  </section>;
}

