const kindLabel: Record<string, string> = { RECEIVED: 'Received by NEXTRON', RETRIEVED: 'Retrieved by NEXTRON', CLAIMED_CREATION: 'Creation time claimed by the file', CLAIMED_PUBLICATION: 'Publication time claimed by the source' };

export function ReconstructionPanel({ caseId }: { caseId: string }) {
  const q = useReconstruction(caseId);
  return <section className={s.panel} aria-label='Reconstruction'>
    <SecHead title='Reconstruction (NEX-REC)' count={q.data?.timeline.length} />
    <Load q={q} rows={3}>{r => !r.result_id ? <p className={s.cap}>Built at the end of each analysis run; none yet.</p> : <>
      {r.conflicts.map(c => <p key={c.finding_id} className={rv.conflict} role='note'><b>Time conflict:</b> {c.title}. {c.description}</p>)}
      <ol className={rv.timeline}>{r.timeline.map((t, i) => { const claimed = t.kind.startsWith('CLAIMED'); return <li key={i} className={rv.point} data-claimed={claimed || undefined}>
        <time>{t.time.slice(0, 10)}<span>{t.time.slice(11, 19)} UTC</span></time>
        <div><b>{kindLabel[t.kind] ?? t.kind}</b><span className={rv.tag}>{claimed ? 'claimed' : 'measured'}</span><small>{t.label} · stated by {t.by}{t.raw ? ` · as written: ${t.raw}` : ''}</small></div>
      </li>; })}</ol>
      <p className={s.cap}>Claimed times (dashed) are the file’s or the source’s own statements and may be wrong; only NEXTRON’s times (solid) are measured.</p>
    </>}</Load>
  </section>;
}
