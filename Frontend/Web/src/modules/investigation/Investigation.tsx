const notBuilt = (e: unknown) => e instanceof ApiError && e.code === 'GRAPH_NOT_BUILT';
const decisionTone: Record<ReviewDecision, Tone> = { ACCEPTED: 'ok', REJECTED: 'alert', INCONCLUSIVE: 'gold', NEEDS_MORE_EVIDENCE: 'steel' };
const decisionLabel: Record<ReviewDecision, string> = { ACCEPTED: 'Accepted', REJECTED: 'Rejected', INCONCLUSIVE: 'Inconclusive', NEEDS_MORE_EVIDENCE: 'Needs more evidence' };
const subjectLabel: Record<ReviewSubject, string> = { FINDING: 'Finding', RELATIONSHIP: 'Relationship', CASE_CONCLUSION: 'Case conclusion', BACKTRACK_COMPARISON: 'Backtracking comparison' };
const edgeLabel: Record<string, string> = { CONTAINS: 'contains', RETRIEVED_AS: 'retrieved as', CANDIDATE_VERSION: 'candidate version of', ABOUT: 'about', CITES: 'cites' };

const NeedCase = ({ what }: { what: string }) => <section className={s.panel}><p className={s.cap}>{what} is built per investigation. Choose one above.</p></section>;

