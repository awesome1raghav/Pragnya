/* Graph, review and reports (plan Step 7). The graph is NEX-EGC's latest stored snapshot: every edge names the record
   that supports it. Reviews (NEX-INV) are the investigator's decisions, versioned and kept apart from findings. Reports
   (NEX-RPT) are generated by a worker as JSON and PDF with their SHA-256; a FINAL needs a reviewed case conclusion. The
   reconstruction panel (NEX-REC) lists dated statements labelled by who states them. */
import Link from 'next/link';
import { useState } from 'react';
import { Download, FileText, Plus } from 'lucide-react';
import s from '@/styles/workspace.module.css';
import p from '@/styles/platform.module.css';
import { api, ApiError, type GraphNode, type GraphSnapshot, type Report, type ReviewDecision, type ReviewSubject } from '@/api';
import { useGraph, usePreferences, useReconstruction, useReports, useReviews } from '@/api/hooks';
import { invalidate } from '@/api/query';
import CaseScope from '@/components/CaseScope';
import { Dot, Empty, Hash, Load, PageHead, SecHead } from '@/components/ui';
import { useWorkspace } from '@/layouts/MainLayout';
import { paths } from '@/config/routes';
import { useCaseContext } from '@/state/CaseContext';
import { utc, type Tone } from '@/utils/labels';

const notBuilt = (e: unknown) => e instanceof ApiError && e.code === 'GRAPH_NOT_BUILT';
const decisionTone: Record<ReviewDecision, Tone> = { ACCEPTED: 'ok', REJECTED: 'alert', INCONCLUSIVE: 'gold', NEEDS_MORE_EVIDENCE: 'steel' };
const decisionLabel: Record<ReviewDecision, string> = { ACCEPTED: 'Accepted', REJECTED: 'Rejected', INCONCLUSIVE: 'Inconclusive', NEEDS_MORE_EVIDENCE: 'Needs more evidence' };
const subjectLabel: Record<ReviewSubject, string> = { FINDING: 'Finding', RELATIONSHIP: 'Relationship', CASE_CONCLUSION: 'Case conclusion' };
const edgeLabel: Record<string, string> = { CONTAINS: 'contains', RETRIEVED_AS: 'retrieved as', CANDIDATE_VERSION: 'candidate version of', ABOUT: 'about', CITES: 'cites' };

const NeedCase = ({ what }: { what: string }) => <section className={s.panel}><p className={s.cap}>{what} is built per investigation. Choose one above.</p></section>;

/* ── graph ── */
export function GraphPage() {
  const { caseId } = useCaseContext();
  return <div className={s.page}>
    <PageHead title='Evidence graph' desc='Evidence, sources and findings of an investigation, and the recorded relationships between them.' />
    <CaseScope />
    {caseId ? <GraphView caseId={caseId} /> : <NeedCase what='The graph' />}
  </div>;
}

export function CaseGraph({ caseId, caseNumber }: { caseId: string; caseNumber: string }) {
  return <div className={s.page}>
    <PageHead title='Evidence graph' desc={`${caseNumber} · built by NEX-EGC from stored records only. Every edge names the record that supports it.`} />
    <GraphView caseId={caseId} />
  </div>;
}

function GraphView({ caseId }: { caseId: string }) {
  const q = useGraph(caseId);
  if (q.error && notBuilt(q.error)) return <Empty title='No graph yet'>The graph is built at the end of each analysis run. Add evidence or start a run.</Empty>;
  return <Load q={q} rows={5}>{g => <div className={p.stack}>
    <div className={p.statGrid}>
      {[['Evidence', g.counts.nodes_evidence], ['Sources', g.counts.nodes_source], ['Findings', g.counts.nodes_finding], ['Edges', g.counts.edges]].map(([k, v]) =>
        <div key={k} className={p.stat}><span>{k}</span><b>{v ?? 0}</b></div>)}
    </div>
    <p className={s.cap}>Snapshot built {utc(g.created_at)}. Candidate relationships and inferences are drawn as recorded; the graph shows what is recorded, not what is true.</p>
    <section className={s.panel} aria-label='Graph drawing'><SecHead title='Graph' />
      <div style={{ overflowX: 'auto' }}><GraphSvg g={g} /></div>{/* on phones it scrolls instead of shrinking the labels */}</section>
    <section className={s.panel} aria-label='Graph edges'>
      <SecHead title='Edges and their records' count={g.edges.length} />
      <EdgeTable g={g} />
    </section>
  </div>}</Load>;
}

function GraphSvg({ g }: { g: GraphSnapshot }) {
  const cols: Record<string, GraphNode[]> = { SOURCE: [], EVIDENCE: [], FINDING: [] };
  g.nodes.forEach(n => cols[n.type]?.push(n));
  const X: Record<string, number> = { SOURCE: 90, EVIDENCE: 330, FINDING: 570 }, gap = 34, top = 40;
  const rows = Math.max(1, ...Object.values(cols).map(c => c.length));
  const pos = new Map<string, { x: number; y: number }>();
  Object.entries(cols).forEach(([t, ns]) => ns.forEach((n, i) => pos.set(n.id, { x: X[t], y: top + i * gap + (rows - ns.length) * gap / 2 })));
  const color: Record<string, string> = { RETRIEVED_AS: '#7fa6bf', CANDIDATE_VERSION: '#e9a23b', ABOUT: '#6d675e', CITES: '#b98fd6' };
  const tone = (n: GraphNode) => n.type === 'FINDING' ? (n.assertion === 'INFERENCE' ? '#e9a23b' : '#8d877c') : n.type === 'SOURCE' ? '#7fa6bf' : '#bdb6aa';
  const h = top + rows * gap + 10;
  return <svg viewBox={`0 0 760 ${h}`} role='img' aria-label={`${g.counts.nodes} nodes, ${g.counts.edges} edges`} style={{ width: '100%', minWidth: 680 }}>
    {['Sources', 'Evidence', 'Findings'].map((t, i) => <text key={t} x={[90, 330, 570][i]} y={16} textAnchor='middle' fontSize={11} fill='#8d877c'>{t}</text>)}
    {g.edges.filter(e => e.type !== 'CONTAINS').map((e, i) => {
      const a = pos.get(e.from), b = pos.get(e.to);
      if (!a || !b) return null;
      if (e.type === 'CANDIDATE_VERSION' || e.type === 'CITES') {
        const bend = (e.type === 'CITES' ? 1 : -1) * (40 + Math.abs(a.y - b.y) / 3);
        return <path key={i} d={`M${a.x} ${a.y} Q${a.x + bend} ${(a.y + b.y) / 2} ${b.x} ${b.y}`} fill='none' stroke={color[e.type]} strokeWidth={1.5} strokeDasharray={e.type === 'CANDIDATE_VERSION' ? '4 3' : undefined} />;
      }
      return <line key={i} x1={a.x} y1={a.y} x2={b.x} y2={b.y} stroke={color[e.type]} strokeWidth={1} opacity={0.7} />;
    })}
    {[...pos.entries()].map(([id, { x, y }]) => { const n = g.nodes.find(v => v.id === id)!; return <g key={id}>
      <circle cx={x} cy={y} r={7} fill='#1c1a17' stroke={tone(n)} strokeWidth={2} />
      <text x={n.type === 'FINDING' ? x + 12 : x - 12} y={y + 4} textAnchor={n.type === 'FINDING' ? 'start' : 'end'} fontSize={12} fill='#bdb6aa'>
        {n.type === 'FINDING' ? `${String(n.module ?? '')} ${String(n.label).toLowerCase().replace(/_/g, ' ')}` : String(n.label)}</text>
    </g>; })}
  </svg>;
}

function EdgeTable({ g }: { g: GraphSnapshot }) {
  const label = new Map(g.nodes.map(n => [n.id, n.type === 'FINDING' ? `${String(n.module)} · ${String(n.title ?? n.label)}` : String(n.label)]));
  const rows = g.edges.filter(e => e.type !== 'CONTAINS');
  if (!rows.length) return <p className={s.cap}>Only the case and its evidence so far; no sources, relationships or findings about evidence.</p>;
  return <div className={p.planWrap}><table className={p.planTable}>
    <thead><tr><th>From</th><th>Relationship</th><th>To</th><th>Supporting record</th></tr></thead>
    <tbody>{rows.map((e, i) => <tr key={i}>
      <td>{label.get(e.from) ?? e.from.slice(0, 8)}</td>
      <td>{edgeLabel[e.type] ?? e.type}{e.type === 'CANDIDATE_VERSION' && <small>candidate · similarity {Number(e.similarity).toFixed(2)}</small>}</td>
      <td>{label.get(e.to) ?? e.to.slice(0, 8)}</td>
      <td><span className={s.mono} style={{ fontSize: 11, overflowWrap: 'anywhere' }}>{e.record}</span></td>
    </tr>)}</tbody>
  </table></div>;
}

/* ── review ── */
export function CaseReview({ caseId, caseNumber, archived }: { caseId: string; caseNumber: string; archived: boolean }) {
  const current = useReviews(caseId, true);
  const all = useReviews(caseId);
  return <div className={s.page}>
    <PageHead title='Review and decisions' desc={`${caseNumber} · your decisions on findings, candidate relationships and the case conclusion. Decisions are versioned and never change the findings they are about.`} />
    <div className={p.grid2}>
      <div className={p.stack}>
        {archived ? <section className={s.panel}><p className={s.cap}>The investigation is archived; reopen it to record decisions.</p></section> : <ReviewForm caseId={caseId} />}
        <section className={s.panel} aria-label='Current decisions'>
          <SecHead title='Current decisions' count={current.data?.length} />
          <Load q={current} rows={3}>{rs => rs.length ? <ul className={p.jobList}>{rs.map(r => <li key={r.review_id} className={p.jobRow}><div>
            <b><span className={s.mono}>{r.review_number}</span> · {subjectLabel[r.subject_type]} <small style={{ display: 'inline' }}>v{r.version}</small></b>
            <small><Dot tone={decisionTone[r.decision]}>{decisionLabel[r.decision]}</Dot> · {r.reviewer} · {utc(r.created_at)}</small>
            <small>{r.rationale}</small>
          </div></li>)}</ul> : <Empty title='No decisions yet'>Choose a subject and record a decision with your reasons.</Empty>}</Load>
        </section>
      </div>
      <section className={s.panel} aria-label='Decision history'>
        <SecHead title='History (every version)' count={all.data?.length} />
        <Load q={all} rows={3}>{rs => rs.length ? <div className={p.planWrap}><table className={p.planTable}>
          <thead><tr><th>Review</th><th>Subject</th><th>Decision</th></tr></thead>
          <tbody>{rs.map(r => <tr key={r.review_id}><td>{r.review_number}<small>{utc(r.created_at)}</small></td><td>{subjectLabel[r.subject_type]} v{r.version}<small className={s.mono}>{r.subject_id.slice(0, 8)}</small></td><td>{decisionLabel[r.decision]}<small>{r.rationale}</small></td></tr>)}</tbody>
        </table></div> : <p className={s.cap}>Nothing recorded.</p>}</Load>
      </section>
    </div>
  </div>;
}

function ReviewForm({ caseId }: { caseId: string }) {
  const { notify } = useWorkspace();
  const graph = useGraph(caseId);
  const rec = useReconstruction(caseId);
  const [subject, setSubject] = useState(`CASE_CONCLUSION:${caseId}`);
  const [decision, setDecision] = useState<ReviewDecision>('INCONCLUSIVE');
  const [rationale, setRationale] = useState('');
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const g = graph.data;
  const findings = g?.nodes.filter(n => n.type === 'FINDING') ?? [];
  const label = new Map(g?.nodes.map(n => [n.id, String(n.label)]) ?? []);
  const relationships = g?.edges.filter(e => e.type === 'CANDIDATE_VERSION') ?? [];
  const submit = async (ev: React.FormEvent) => {
    ev.preventDefault();
    const [subject_type, subject_id] = subject.split(':') as [ReviewSubject, string];
    setBusy(true); setError(null);
    try { const r = await api.reviews.create(caseId, { subject_type, subject_id, decision, rationale }); notify(`${r.review_number} recorded (version ${r.version})`); setRationale(''); invalidate(`case:${caseId}`); }
    catch (e) { setError(e instanceof ApiError ? e.message : 'The decision could not be recorded'); }
    finally { setBusy(false); }
  };
  return <section className={s.panel} aria-label='Record a decision'>
    <SecHead title='Record a decision' />
    <form onSubmit={submit} className={p.form}>
      <label className={s.field}><span>Subject</span><select className={s.input} value={subject} onChange={e => setSubject(e.target.value)} aria-label='Review subject'>
        <option value={`CASE_CONCLUSION:${caseId}`}>Case conclusion{rec.data?.result_id ? '' : ' (needs a reconstruction first)'}</option>
        {findings.length > 0 && <optgroup label='Findings'>{findings.map(f => <option key={f.id} value={`FINDING:${f.id}`}>{String(f.module)} · {String(f.title ?? f.label)}</option>)}</optgroup>}
        {relationships.length > 0 && <optgroup label='Candidate relationships'>{relationships.map(e => <option key={e.record} value={`RELATIONSHIP:${e.record.split(':')[1]}`}>{label.get(e.from)} ↔ {label.get(e.to)} ({String(e.kind)})</option>)}</optgroup>}
      </select></label>
      <label className={s.field}><span>Decision</span><select className={s.input} value={decision} onChange={e => setDecision(e.target.value as ReviewDecision)} aria-label='Decision'>
        {(Object.keys(decisionLabel) as ReviewDecision[]).map(d => <option key={d} value={d}>{decisionLabel[d]}</option>)}</select></label>
      <label className={s.field}><span>Rationale (required, kept with the decision)</span>
        <textarea className={s.input} rows={3} required minLength={3} maxLength={4000} value={rationale} onChange={e => setRationale(e.target.value)} aria-label='Rationale' /></label>
      <button className={`${s.btn} ${s.primary}`} disabled={busy || rationale.trim().length < 3}><Plus size={15} />{busy ? 'Recording…' : 'Record decision'}</button>
    </form>
    {error && <p className={p.fieldError} role='alert'>{error}</p>}
  </section>;
}

