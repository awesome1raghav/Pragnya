function ReportsView({ caseId, archived }: { caseId: string; archived: boolean }) {
  const { notify } = useWorkspace();
  const q = useReports(caseId);
  const progress = useProgress([caseId]).data?.[0];
  const [error, setError] = useState<string | null>(null);
  const request = async (kind: 'DRAFT' | 'FINAL') => {
    setError(null);
    try { const r = await api.reports.create(caseId, kind); notify(`${r.report_number} (${kind.toLowerCase()}) queued`); invalidate(`case:${caseId}`, 'jobs'); }
    catch (e) { setError(e instanceof ApiError ? e.message : 'The report could not be requested'); }
  };
  return <div className={p.stack}>
    <section className={s.panel} aria-label='What a report contains'>
      <SecHead title='What the report will contain' />
      <ul className={rv.contents}>
        <li><b>Evidence inventory</b>{progress ? `${progress.evidence} item${progress.evidence === 1 ? '' : 's'}, each with its SHA-256` : 'each item with its SHA-256'}</li>
        <li><b>Every method’s result</b>at its level (observation, inference), with thresholds and limitations</li>
        <li><b>Candidate relationships and timeline</b>as recorded, claims labelled as claims</li>
        <li><b>Your decisions</b>{progress?.conclusion ? `conclusion: ${progress.conclusion.toLowerCase().replace(/_/g, ' ')}` : 'no case conclusion yet'}</li>
      </ul>
      {progress && <p className={rv.ready}><span data-ok={progress.evidence > 0}>{progress.evidence > 0 ? '✓' : '·'} evidence</span><span data-ok={!progress.runs_active && !!progress.last_run_state}>{progress.runs_active ? '· analysis running' : progress.last_run_state ? '✓ analysed' : '· not analysed'}</span><span data-ok={!!progress.conclusion}>{progress.conclusion ? '✓ conclusion recorded' : '· conclusion needed for a final report'}</span></p>}
    </section>
    {!archived && <section className={s.panel} aria-label='Generate a report'>
      <SecHead title='Generate a report' />
      <div style={{ display: 'flex', gap: 8, flexWrap: 'wrap' }}>
        <button className={`${s.btn} ${s.primary}`} onClick={() => request('DRAFT')}><FileText size={15} />Draft report</button>
        <button className={s.btn} onClick={() => request('FINAL')}><FileText size={15} />Final report</button>
      </div>
      <p className={s.cap}>A draft can be generated at any time. A final report needs a reviewed case conclusion (<Link href={paths.caseReview(caseId)} style={{ textDecoration: 'underline' }}>Review</Link>).</p>
      {error && <p className={p.fieldError} role='alert'>{error}</p>}
    </section>}
    <section className={s.panel} aria-label='Report versions'>
      <SecHead title='Versions' count={q.data?.length} />
      <Load q={q} rows={3}>{rs => rs.length ? <ul className={p.jobList}>{rs.map(r => <ReportRow key={r.report_id} r={r} />)}</ul>
        : <Empty title='No reports yet'>Generate a draft to freeze the current state of the investigation.</Empty>}</Load>
    </section>
  </div>;
}

function ReportRow({ r }: { r: Report }) {
  const tone: Tone = r.state === 'GENERATED' ? 'ok' : r.state === 'FAILED' ? 'alert' : 'steel';
  const sm = r.summary as { evidence?: number; findings?: number; reviews?: number; conclusion?: string | null };
  const first = usePreferences().data?.preferences.reports.default_download ?? 'pdf';  // the preferred format comes first
  const formats = first === 'json' ? ['json', 'pdf'] as const : ['pdf', 'json'] as const;
  return <li className={rv.version} aria-label={`${r.report_number} version ${r.version}`}>
    <div>
      <b><span className={s.mono}>{r.report_number}</span> · version {r.version} · {r.kind === 'FINAL' ? 'Final' : 'Draft'}</b>
      <small><Dot tone={tone}>{r.state === 'GENERATED' ? 'Generated' : r.state === 'FAILED' ? 'Failed' : 'Generating'}</Dot> · requested by {r.requested_by} · {utc(r.created_at)}</small>
      {r.state === 'GENERATED' && <small>{sm.evidence} evidence · {sm.findings} findings · {sm.reviews} decisions · conclusion {sm.conclusion ? sm.conclusion.toLowerCase().replace(/_/g, ' ') : 'not reviewed'}</small>}
      {r.error && <small>{r.error}</small>}
      {r.state === 'GENERATED' && <span className={rv.links}><Link href={paths.caseEvidence(r.case_id)}>Evidence it covers</Link><Link href={paths.caseReview(r.case_id)}>Decisions it records</Link><Link href={paths.caseAnalysis(r.case_id)}>Analysis behind it</Link></span>}
      {(r.pdf_sha256 || r.json_sha256) && <details className={rv.hashes}><summary>Integrity: SHA-256 of each file</summary><div>
        {r.pdf_sha256 && <Hash value={r.pdf_sha256} label='PDF SHA-256' />}
        {r.json_sha256 && <Hash value={r.json_sha256} label='JSON SHA-256' />}
      </div></details>}
    </div>
    {r.state === 'GENERATED' && <div className={rv.dl}>
      {formats.map(f => <a key={f} className={`${s.btn} ${s.sm} ${f === formats[0] ? s.primary : ''}`} href={api.reports.downloadUrl(r.report_id, f)} download
        aria-label={`Download ${r.report_number} ${f.toUpperCase()}`}><Download size={13} />{f.toUpperCase()}</a>)}
    </div>}
  </li>;
}

